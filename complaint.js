function g(d, m, f) { return d.gender === "f" ? f : m; }

function fmtDate(iso) {
  if (!iso) return "____";
  const [y, m, dd] = iso.split("-");
  return `${dd}.${m}.${y}`;
}

function shortFio(fio) {
  const p = (fio || "").trim().split(/\s+/);
  if (!p[0]) return "____";
  return p[0] + (p[1] ? " " + p[1][0] + "." : "") + (p[2] ? p[2][0] + "." : "");
}

// Последний день подачи: 10 дней со следующего дня после получения копии,
// выходной переносится на понедельник. Праздники не учитываются
function deadline(copyIso) {
  if (!copyIso) return null;
  const d = new Date(copyIso + "T12:00:00");
  d.setDate(d.getDate() + 10);
  if (d.getDay() === 6) d.setDate(d.getDate() + 2);
  if (d.getDay() === 0) d.setDate(d.getDate() + 1);
  return d;
}

function isoOf(d) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

function todayIso() { return isoOf(new Date()); }

function isLate(d) {
  const dl = deadline(d.copyDate);
  if (!dl) return false;
  return isoOf(dl) < (d.signDate || todayIso());
}

function selectedArgs(d) {
  const list = ARGS.common.concat(ARGS[d.topic] || []);
  return list.filter(a => d.args && d.args[a.id]);
}

function fineText(d) {
  return d.fine === "warn" ? "предупреждения" : "административного штрафа в размере " + (d.fineSum || "500") + " рублей";
}

