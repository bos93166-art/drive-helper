function blocksToText(B) {
  return B.map(b => {
    if (b.k === "gap") return "";
    if (b.k === "li") return b.n + ". " + b.t;
    if (b.k === "p") return "    " + b.t;
    return b.t;
  }).join("\n");
}

function blocksToPdf(B) {
  const nb = t => String(t).replace(/(№|ст\.|ч\.|п\.) /g, "$1\u00A0");
  const content = B.map(b0 => {
    const b = Object.assign({}, b0, { t: nb(b0.t) });
    switch (b.k) {
      case "gap": return { text: " ", margin: [0, 2] };
      case "right": return { text: b.t, margin: [240, 0, 0, 0] };
      case "title": return { text: b.t, alignment: "center", bold: true, margin: [0, 6, 0, 2] };
      case "center": return { text: b.t, alignment: "center" };
      case "li": return { text: b.n + ". " + b.t, alignment: "justify", margin: [0, 3, 0, 3] };
      case "p": return { text: b.t, alignment: "justify", leadingIndent: 28, margin: [0, 3, 0, 3] };
      case "sign": return { text: b.t, margin: [0, 10, 0, 0] };
      default: return { text: b.t };
    }
  });
  return { content, pageMargins: [70, 50, 50, 50], defaultStyle: { fontSize: 12, lineHeight: 1.2 } };
}

